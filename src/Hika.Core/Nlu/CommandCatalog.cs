namespace Hika.Nlu;

/// <summary>
/// Все команды, описанные устройством фразы.
///
/// Разделы взяты не с потолка. Голосовое управление Windows, распознавание
/// речи Windows и известные ассистенты сходятся на одном и том же наборе:
