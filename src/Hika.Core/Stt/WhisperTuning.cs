namespace Hika.Stt;

/// <summary>
/// Настройка распознавания под длину фразы.
///
/// Здесь лежит самый большой запас по отзывчивости во всей программе, и стоит
/// объяснить, откуда он берётся.
///
/// Whisper всегда работает окном в тридцать секунд. Сколько бы человек ни
/// сказал — «Ави, открой стим» длится две секунды, — модель дополняет запись
/// тишиной до тридцати и прогоняет через кодировщик всё окно целиком.
/// Двадцать восемь секунд из тридцати уходят на обработку тишины, которую
/// мы сами же и дописали.
///
/// У whisper.cpp есть параметр audio_ctx, обрезающий это окно. Тридцать секунд
/// звука дают полторы тысячи позиций кодировщика — ровно пятьдесят на секунду.
/// Значит, для двухсекундной команды достаточно ста с небольшим, и работы
/// остаётся в разы меньше. Слышно это сразу: команда выполняется, пока человек
/// ещё не отвёл взгляд, а не через несколько секунд.
///
/// Расплата — модель не обучалась на обрезанном окне, и при слишком жёсткой
/// обрезке качество падает. Поэтому запас щедрый, а размеры округляются
/// до нескольких ступеней: точная подгонка ничего не даст, зато заставит
/// пересобирать обвязку модели на каждую фразу.
/// </summary>
public static class WhisperTuning
{
    /// <summary>Полное окно: тридцать секунд звука.</summary>
    public const int FullContext = 1500;

    /// <summary>Позиций кодировщика на секунду звука.</summary>
    private const int FramesPerSecond = 50;

    /// <summary>
    /// Запас сверх самой речи.
    ///
    /// Нужен не для красоты: модель понимает, что фраза кончилась, увидев
    /// после неё тишину. Обрезав окно ровно по последнему слову, мы отнимаем
    /// у неё этот признак — и получаем оборванные и повторяющиеся окончания.
    /// Две секунды тишины сверху этого не допускают.
    /// </summary>
    private const int Margin = FramesPerSecond * 2;

    /// <summary>
    /// Ступени размера окна.
    ///
    /// Ступени, а не точное значение, потому что смена размера означает
    /// пересборку обвязки модели — десятки миллисекунд и заново выделенная
    /// память. Команды человека почти всегда укладываются в первую ступень,
    /// и после первой же фразы размер перестаёт меняться вовсе.
    /// </summary>
    private static readonly int[] Steps = { 320, 640, 1024, FullContext };

    /// <summary>Размер окна, которого хватит для записи такой длины.</summary>
    public static int AudioContextFor(double seconds)
    {
        if (seconds <= 0) return Steps[0];

        var needed = (int)Math.Ceiling(seconds * FramesPerSecond) + Margin;

        foreach (var step in Steps)
        {
            if (needed <= step) return step;
        }

        return FullContext;
    }

    public static int AudioContextForSamples(int samples, int sampleRate = 16000)
        => AudioContextFor(sampleRate <= 0 ? 0 : samples / (double)sampleRate);

    /// <summary>
    /// Стоит ли менять размер окна.
    ///
    /// Расти разрешаем сразу: не хватило места — обрежется речь, а это прямая
    /// потеря. Уменьшаться — только когда короткие фразы повторились несколько
    /// раз подряд, иначе одна длинная реплика посреди коротких заставит
    /// пересобирать обвязку туда и обратно.
    /// </summary>
    public static bool ShouldSwitch(int current, int wanted, int shorterInARow)
        => wanted > current || (wanted < current && shorterInARow >= 3);
}
